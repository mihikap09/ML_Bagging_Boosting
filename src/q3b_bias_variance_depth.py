def depth_from_code(depth_code):
    """
    Convert -1 into the sklearn value None.
    """
    if depth_code == -1:
        return None

    return int(depth_code)


def create_stratified_resample(
    repetition_index
):
    """
    Sample six observations with replacement independently
    within every identity.
    """
    rng = np.random.default_rng(
        SEED + 100000 + repetition_index
    )

    positions = []

    for class_label in range(N_CLASSES):
        class_positions = np.flatnonzero(
            y_original_train == class_label
        )

        sampled_positions = rng.choice(
            class_positions,
            size=SAMPLES_PER_CLASS,
            replace=True
        )

        positions.extend(
            sampled_positions.tolist()
        )

    positions = np.asarray(
        positions,
        dtype=np.int64
    )

    assert len(positions) == 240

    sampled_labels = y_original_train[
        positions
    ]

    for class_label in range(N_CLASSES):
        assert (
            np.sum(
                sampled_labels == class_label
            )
            == SAMPLES_PER_CLASS
        )

    return positions


def map_probabilities(
    probability_matrix,
    model_classes
):
    """
    Map predict_proba output into all 40 class columns.
    """
    complete_probabilities = np.zeros(
        (
            probability_matrix.shape[0],
            N_CLASSES
        ),
        dtype=np.float64
    )

    complete_probabilities[
        :,
        model_classes.astype(np.int64)
    ] = probability_matrix

    return complete_probabilities


def leaf_statistics(
    tree,
    evaluation_X
):
    """
    Calculate occupancy statistics using observations passed
    through the fitted tree.

    Returns:
        number of occupied leaves;
        mean observations per occupied leaf;
        minimum leaf occupancy;
        fraction of leaves at the configured minimum size.
    """
    leaf_ids = tree.apply(
        evaluation_X
    )

    _, leaf_counts = np.unique(
        leaf_ids,
        return_counts=True
    )

    number_of_leaves = len(leaf_counts)

    mean_occupancy = float(
        np.mean(leaf_counts)
    )

    minimum_occupancy = int(
        np.min(leaf_counts)
    )

    minimum_size_fraction = float(
        np.mean(
            leaf_counts
            <= MIN_SAMPLES_LEAF
        )
    )

    return (
        number_of_leaves,
        mean_occupancy,
        minimum_occupancy,
        minimum_size_fraction
    )


def disagreement_from_vote_counts(
    vote_counts,
    number_of_trees
):
    """
    Average pairwise tree disagreement on the fixed test set.

    For each test observation, count agreeing pairs using its
    class vote counts, then average disagreement over all
    observations.
    """
    total_pairs = (
        number_of_trees
        * (number_of_trees - 1)
        / 2
    )

    agreeing_pairs = np.sum(
        vote_counts
        * (vote_counts - 1)
        / 2,
        axis=1
    )

    disagreement_per_observation = (
        total_pairs - agreeing_pairs
    ) / total_pairs

    return float(
        np.mean(
            disagreement_per_observation
        )
    )


def calculate_bias_and_variance(
    outputs
):
    """
    outputs shape:
        repetitions x test observations x classes
    """
    mean_output = np.mean(
        outputs,
        axis=0
    )

    bias_squared = float(
        np.mean(
            np.sum(
                (
                    mean_output
                    - test_one_hot
                ) ** 2,
                axis=1
            )
        )
    )

    variance = float(
        np.mean(
            np.sum(
                (
                    outputs
                    - mean_output[
                        np.newaxis,
                        :,
                        :
                    ]
                ) ** 2,
                axis=2
            )
        )
    )

    return bias_squared, variance


