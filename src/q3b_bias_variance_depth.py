"""
Question 3(b): Effect of tree depth on measured bias and variance.

Depth regimes:
    shallow:       max_depth=2
    deeper finite: max_depth=16
    selected:      max_depth=None

At each depth, compare:

1. One decision tree.
2. A manually implemented 100-tree bagged ensemble.

The clean test set remains fixed. Thirty training sets are
generated by sampling six observations with replacement within
each identity's original six training observations.

For each depth and model, measure:

- squared bias;
- variance;
- mean and standard deviation of test accuracy;
- leaf occupancy;
- tree disagreement for bagging;
- accuracy improvement from bagging;
- absolute and percentage variance removed by bagging.

The script checkpoints after every completed depth/refit pair.
"""

